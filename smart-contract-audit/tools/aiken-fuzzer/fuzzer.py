#!/usr/bin/env python3
"""
fuzzer.py — Main entry point for the Aiken smart contract fuzzer.

Generates random and edge-case redeemer/datum inputs from a Plutus blueprint,
runs `aiken check` with generated test modules, and reports any unexpected
behaviors that may indicate vulnerabilities.

Usage:
    python fuzzer.py --contract ./path/to/contract --cases 100 --seed 42
    python fuzzer.py --contract ./path/to/contract --blueprint ./path/to/plutus.json
    python fuzzer.py --contract ./path/to/contract --validator "simple_escrow.simple_escrow.spend"
    python fuzzer.py --list-validators --contract ./path/to/contract

The fuzzer operates in two modes:
  1. Schema-analysis mode: parses the blueprint and reports what types are used
  2. Test-generation mode: writes Aiken test files and runs `aiken check`
"""

