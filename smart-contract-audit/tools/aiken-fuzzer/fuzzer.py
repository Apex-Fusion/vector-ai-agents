def main():
    parser = argparse.ArgumentParser(
        description="Aiken smart contract fuzzer — generates random inputs from Plutus blueprints",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Fuzz all validators in a contract (100 cases, random seed)
  python fuzzer.py --contract /path/to/contracts

  # Fuzz specific validator, 500 cases, reproducible seed
  python fuzzer.py --contract /path/to/contracts \\
    --validator "simple_escrow.simple_escrow.spend" \\
    --cases 500 --seed 42

  # List available validators
  python fuzzer.py --contract /path/to/contracts --list-validators

  # Use explicit blueprint path
  python fuzzer.py --contract /path/to/contracts \\
    --blueprint /path/to/plutus.json --cases 200

  # Verbose output with custom output directory
  python fuzzer.py --contract /path/to/contracts \\
    --output ./fuzz-results --verbose
        """,
    )

    parser.add_argument("--contract", required=True,
                        help="Path to Aiken contract directory (containing aiken.toml)")
    parser.add_argument("--blueprint", default=None,
                        help="Path to plutus.json (default: auto-detect in --contract dir)")
    parser.add_argument("--validator", default=None,
                        help="Validator title to fuzz (default: first .spend validator)")
    parser.add_argument("--cases", type=int, default=100,
                        help="Number of fuzz cases to generate (default: 100)")
    parser.add_argument("--seed", type=int, default=None,
                        help="Random seed for reproducibility (default: random)")
    parser.add_argument("--output", default=None,
                        help="Output directory for reports and artifacts")
    parser.add_argument("--list-validators", action="store_true",
                        help="List all validators in the blueprint and exit")
    parser.add_argument("--describe-schema", action="store_true",
                        help="Print the type schema for the target validator and exit")
    parser.add_argument("--verbose", "-v", action="store_true",
                        help="Verbose output")

    args = parser.parse_args()

    # Resolve blueprint
    blueprint_path = args.blueprint
    if not blueprint_path:
        try:
            blueprint_path = find_blueprint(args.contract)
        except FileNotFoundError as e:
            print(f"Error: {e}", file=sys.stderr)
            sys.exit(1)

    # List validators mode
    if args.list_validators:
        try:
            bp = parse_blueprint(blueprint_path)
            print(f"Validators in {blueprint_path}:")
            for v in bp.list_validators():
                print(f"  {v}")
        except Exception as e:
            print(f"Error: {e}", file=sys.stderr)
            sys.exit(1)
        return

    # Describe schema mode
    if args.describe_schema:
        try:
            bp = parse_blueprint(blueprint_path)
            validators = bp.list_validators()
            target = args.validator
            if not target:
                spend = [v for v in validators if v.endswith(".spend")]
                target = spend[0] if spend else validators[0]

            info = bp.get_validator(target)
            print(f"Validator: {target}")
            if info["redeemer_type"]:
                print(f"\nREDEEMER ({info['redeemer_title']}):")
                print(describe_type(info["redeemer_type"], 1))
            if info["datum_type"]:
                print(f"\nDATUM ({info['datum_title']}):")
                print(describe_type(info["datum_type"], 1))
        except Exception as e:
            print(f"Error: {e}", file=sys.stderr)
            sys.exit(1)
        return

    # Run fuzz session
    try:
        result = run_fuzz_session(
            contract_dir=args.contract,
            num_cases=args.cases,
            seed=args.seed,
            validator_title=args.validator,
            blueprint_path=blueprint_path,
            output_dir=args.output,
            verbose=args.verbose,
        )
    except (FileNotFoundError, ValueError, KeyError) as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)

    # Print summary
    output_dir = args.output or os.path.join(args.contract, "fuzz-output")
    report_path = os.path.join(output_dir, "fuzz-report.md")

    print(f"\n{'='*60}")
    print(f"Fuzz Session Complete")
    print(f"{'='*60}")
    print(f"Validator:  {result.validator_title}")
    print(f"Cases:      {result.total_cases}")
    print(f"Seed:       {result.seed if result.seed is not None else '(random)'}")
    print(f"")
    print(f"Results:")
    print(f"  Unexpected:          {len(result.unexpected)}")
    print(f"  Potential vulns:     {len(result.vulnerabilities)}")
    print(f"")
    print(f"Output dir: {output_dir}")
    print(f"Report:     {report_path}")

    if result.vulnerabilities:
        print(f"\n🚨 POTENTIAL VULNERABILITIES FOUND: {len(result.vulnerabilities)}")
        print(f"   Review {report_path} immediately!")
        sys.exit(2)  # Non-zero exit for CI integration
    else:
        print(f"\n✅ No structural vulnerabilities detected in {result.total_cases} cases.")
        sys.exit(0)


if __name__ == "__main__":
    main()
