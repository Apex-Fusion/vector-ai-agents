# ---------------------------------------------------------------------------
# Blueprint parsing
# ---------------------------------------------------------------------------

def parse_blueprint(plutus_json_path: str) -> BlueprintParser:
    """
    Load and parse a Plutus blueprint JSON file.

    Returns a BlueprintParser with all validators and type definitions.
    """
    path = Path(plutus_json_path)
    if not path.exists():
        raise FileNotFoundError(f"Blueprint not found: {plutus_json_path}")
    return BlueprintParser.from_file(str(path))


def find_blueprint(contract_dir: str) -> str:
    """Locate plutus.json in a contract directory."""
    candidates = [
        os.path.join(contract_dir, "plutus.json"),
        os.path.join(contract_dir, "build", "plutus.json"),
    ]
    for path in candidates:
        if os.path.exists(path):
            return path
    raise FileNotFoundError(
        f"No plutus.json found in {contract_dir}. "
        "Run `aiken build` first, or specify --blueprint."
    )


# ---------------------------------------------------------------------------
# Redeemer generation
# ---------------------------------------------------------------------------

def generate_random_redeemer(schema: Optional[AikenType], seed: Optional[int] = None) -> Any:
    """
    Generate a single random redeemer value for the given schema.

    Args:
        schema: Parsed AikenType (from BlueprintParser)
        seed: Optional random seed for reproducibility

    Returns:
        A Python value representing the Plutus redeemer data.
        Use generators.to_json_value() to convert to JSON-serializable form.
    """
    gen = ValueGenerator(seed=seed)
    return gen.generate(schema)


def generate_edge_cases(schema: Optional[AikenType]) -> list[Any]:
    """
    Generate boundary and edge case values for the given schema.

    Covers: None, 0, max int, min int, empty lists, wrong constructor indices,
    empty byte arrays, too-short/too-long hashes, etc.

    Returns:
        List of Python values to test against.
    """
    gen = ValueGenerator(seed=0)  # fixed seed for reproducibility of edge cases
    return gen.generate_edge_cases(schema)


